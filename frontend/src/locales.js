export function normalizeLocale(value) {
  const locale = String(value || '').trim().replace('_', '-').toLowerCase();
  if (locale === 'zh' || locale.startsWith('zh-')) return 'zh-CN';
  if (locale === 'en' || locale.startsWith('en-')) return 'en';
  return null;
}

export function detectLocale(storedLocale, browserLocales = []) {
  const stored = normalizeLocale(storedLocale);
  if (stored) return stored;
  for (const locale of browserLocales || []) {
    const normalized = normalizeLocale(locale);
    if (normalized) return normalized;
  }
  return DEFAULT_LOCALE;
}

function selectMessage(message, locale, variables) {
  if (typeof message === 'string') return message;
  if (!message || typeof message !== 'object') return '';
  const rule = new Intl.PluralRules(locale).select(Number(variables.count));
  return message[rule] ?? message.other ?? message.one ?? '';
}

export function translate(locale, key, variables = {}) {
  const normalized = normalizeLocale(locale) || DEFAULT_LOCALE;
  const message = messages[normalized]?.[key] ?? messages[DEFAULT_LOCALE]?.[key];
  if (message == null) {
    console.warn(`[i18n] Missing message: ${key}`);
    return key;
  }
  const numberFormatter = new Intl.NumberFormat(normalized);
  return selectMessage(message, normalized, variables).replace(/\{([a-zA-Z0-9_]+)\}/g, (match, name) => {
    if (!Object.prototype.hasOwnProperty.call(variables, name)) return match;
    const value = variables[name];
    return typeof value === 'number' && Number.isFinite(value) ? numberFormatter.format(value) : String(value);
  });
}

function placeholders(value) {
  const variants = typeof value === 'string' ? [value] : Object.values(value || {});
  return [...new Set(variants.flatMap(item => [...String(item).matchAll(/\{([a-zA-Z0-9_]+)\}/g)].map(match => match[1])))].sort();
}

export function validateCatalogs(catalogs = messages) {
  const baseCatalog = catalogs[DEFAULT_LOCALE] || {};
  const baseKeys = Object.keys(baseCatalog).sort();
  const errors = [];
  for (const locale of SUPPORTED_LOCALES.map(item => item.id)) {
    const localeKeys = Object.keys(catalogs[locale] || {}).sort();
    const missing = baseKeys.filter(key => !localeKeys.includes(key));
    const extra = localeKeys.filter(key => !baseKeys.includes(key));
    if (missing.length) errors.push(`${locale}: missing ${missing.join(', ')}`);
    if (extra.length) errors.push(`${locale}: extra ${extra.join(', ')}`);
    for (const key of localeKeys) {
      const value = catalogs[locale][key];
      const valid = typeof value === 'string' || (value && typeof value === 'object' && Object.values(value).every(item => typeof item === 'string'));
      if (!valid) {
        errors.push(`${locale}: ${key} must be a string or plural map`);
        continue;
      }
      const expected = placeholders(baseCatalog[key]).join(',');
      const actual = placeholders(value).join(',');
      if (actual !== expected) errors.push(`${locale}: ${key} placeholders [${actual}] do not match [${expected}]`);
    }
  }
  return errors;
}
